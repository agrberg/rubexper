#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes src/parser/properties.ts from every \p{...} name this Ruby accepts. The gem omits aliases
# such as L, Lu, and Latn, so candidates also include every 1-4 letter name.
require 'regexp_parser'

def accepted?(name)
  Regexp.new("\\p{#{name}}")
  true
rescue RegexpError
  false
end

normalize = ->(name) { name.to_s.downcase.delete('_ -') }
candidates = Regexp::Syntax::Token::UnicodeProperty::All.map(&normalize)
('a'..'z').to_a.then do |letters|
  (1..4).each { |len| letters.repeated_permutation(len) { |chars| candidates << chars.join } }
end

names = candidates.uniq.select { |name| accepted?(name) }.sort
path = File.expand_path('../src/parser/properties.ts', __dir__)
File.write(path, <<~TS)
  // Generated by bin/gen-properties.rb on Ruby #{RUBY_VERSION}. Do not edit.
  export const PROPERTY_NAMES: ReadonlySet<string> = new Set(#{names.inspect.gsub('"', "'")});
TS
puts "#{names.size} names written to #{path}"
